/* Writes docs/SUITES.md: every end-to-end suite, in the area tests/regression.mjs puts it in, with what it says it
   checks (the first paragraph of its own header comment, or failing that the headings it prints), and the number of
   checks the last regression run counted for it. Generated, never edited by hand:

     node tools/suite-catalogue.cjs [path-to-report.json]

   so the catalogue cannot drift from the suites the way a hand-kept list does. */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const e2e = path.join(root, 'tests', 'e2e');
const regression = fs.readFileSync(path.join(root, 'tests', 'regression.mjs'), 'utf8');

/* The areas, read from the gate itself so the two cannot disagree. */
const areaSource = regression.slice(regression.indexOf('const AREAS = ['), regression.indexOf('const areaOf'));
const AREAS = [];
for (const match of areaSource.matchAll(/\['([a-z-]+)',\s*(\/.*\/)\]/g)) AREAS.push([match[1], new Function(`return ${match[2]}`)()]);
const areaOf = (name) => (AREAS.find(([, re]) => re.test(name)) || ['other'])[0];

const counts = {};
const reportPath = process.argv[2];
if (reportPath && fs.existsSync(reportPath)) {
  for (const suite of JSON.parse(fs.readFileSync(reportPath, 'utf8')).suites || []) {
    const last = suite.attempts[suite.attempts.length - 1];
    counts[suite.name] = last.tally ? last.tally.total : '';
  }
}

function describe(file) {
  const text = fs.readFileSync(file, 'utf8');
  /* The header: the comments before the first line of code. A comment in the middle of the file is about a line, not the suite. */
  const firstCode = text.search(/^(import|const|let|var|async|await|\(|\/\/ eslint|'use strict')/m);
  const head = firstCode > 0 ? text.slice(0, firstCode) : text.slice(0, 2000);
  const blocks = [...head.matchAll(/\/\*([\s\S]*?)\*\//g)].map((m) => m[1]);
  /* not the licence, and not the boilerplate "Part of the end-to-end suite. See README" that says nothing about this one */
  const doc = blocks.find((block) => !/Copyright|Licensed under/.test(block) && !/^\s*\*?\s*Part of the P00RIJA end-to-end suite/.test(block) && block.replace(/[\s*]/g, '').length > 30);
  if (doc) {
    const cleaned = doc.split('\n').map((line) => line.replace(/^\s*\*? ?/, '')).join('\n').trim();
    const paragraph = cleaned.split(/\n\s*\n/)[0].replace(/\s+/g, ' ').trim();
    return paragraph.length > 420 ? `${paragraph.slice(0, 417)}…` : paragraph;
  }
  const headings = [...text.matchAll(/console\.log\(['"`]\\n=+ (.+?) =+/g)].map((m) => m[1]).filter((h) => !/\$\{|failed of|failing of/.test(h));
  if (headings.length) return `Sections it prints: ${headings.slice(0, 7).join('; ')}.`;
  const checks = [...text.matchAll(/check\(\s*['"`]([^'"`]{12,90})['"`]/g)].map((m) => m[1]);
  return checks.length ? `Checks, among others: ${checks.slice(0, 3).join('; ')}.` : '(no description in the file)';
}

const suites = fs.readdirSync(e2e).filter((f) => f.endsWith('.mjs') && !f.startsWith('_') && f !== 'run-all.mjs').map((f) => f.replace(/\.mjs$/, '')).sort();
const byArea = new Map();
for (const name of suites) {
  const area = areaOf(name);
  if (!byArea.has(area)) byArea.set(area, []);
  byArea.get(area).push(name);
}
const out = ['# End-to-end suites', '', `Generated by \`node tools/suite-catalogue.cjs\` — ${suites.length} suites. What a suite says it checks is the first paragraph of its own header; run any one with \`node tests/e2e/<name>.mjs\` (it needs a stack: \`node tests/e2e/_local-stack.mjs <name>\` starts an isolated one) or all of them with \`node tests/regression.mjs\` (see docs/REGRESSION.md).`, ''];
for (const [area, names] of [...byArea.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  out.push(`## ${area} (${names.length})`, '');
  for (const name of names) out.push(`- **${name}**${counts[name] ? ` (${counts[name]} checks)` : ''} — ${describe(path.join(e2e, `${name}.mjs`))}`);
  out.push('');
}
fs.writeFileSync(path.join(root, 'docs', 'SUITES.md'), `${out.join('\n')}\n`);
console.log(`wrote docs/SUITES.md (${suites.length} suites)`);
